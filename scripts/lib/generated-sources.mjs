/** Serialize data for generated JavaScript/TypeScript without creating syntax. */
export function sourceLiteral(value) {
	const serialized = JSON.stringify(value);
	if (serialized === undefined) throw new Error('Cannot serialize generated value');
	// These are JavaScript line terminators, including inside source comments.
	return serialized.replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

export function localeCode(value) {
	if (
		typeof value !== 'string' ||
		value.length > 64 ||
		!/^[a-z]{2,8}(?:-[a-z0-9]{2,8})*$/.test(value)
	) {
		throw new Error('Invalid locale code');
	}
	return value;
}

export function versionId(value) {
	if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < 1) {
		throw new Error('Invalid version ID');
	}
	return value;
}

function bookId(value) {
	// USFM book identifiers are three ASCII letters/digits (e.g. GEN, 1CO).
	if (typeof value !== 'string' || !/^(?=.*[A-Z])[A-Z0-9]{3}$/.test(value)) {
		throw new Error('Invalid book ID');
	}
	return value;
}

export function knownBookId(value, ids) {
	const id = bookId(value);
	if (!ids.has(id)) throw new Error('Unknown book ID');
	return id;
}

function languageTag(value) {
	if (
		typeof value !== 'string' ||
		value.length > 64 ||
		!/^[A-Za-z]{2,8}(?:-[A-Za-z0-9]{1,8})*$/.test(value)
	) {
		throw new Error('Invalid language tag');
	}
	return value;
}

function text(value, label) {
	if (typeof value !== 'string' || value.length === 0) throw new Error(`Invalid ${label}`);
	return value;
}

/** Render one book as an object literal; callable without provider access. */
export function bookRow(row) {
	return `{ usfm: ${sourceLiteral(bookId(row.usfm))}, slug: ${sourceLiteral(text(row.slug, 'book slug'))}, name: ${sourceLiteral(text(row.name, 'book name'))} }`;
}

/** Include source metadata safely: a newline must not escape the comment. */
export function bookTableSource(locale, rows) {
	const code = localeCode(locale.code);
	if (locale.prefix !== code) throw new Error('Locale prefix does not match locale code');
	const name = text(locale.englishName, 'locale name');
	const id = versionId(locale.defaultVersionId);
	const body = rows.map((row) => `\t${bookRow(row)},`).join('\n');
	return (
		`// Generated by scripts/generate-book-slugs.mjs — do not edit by hand.\n` +
		`// Source: ${sourceLiteral(name)} book titles from version ${sourceLiteral(id)}.\n` +
		`import type { LocalizedBook } from './types';\n\n` +
		`export const BOOKS: readonly LocalizedBook[] = [\n${body}\n];\n`
	);
}

/** Render a locale as an object literal; callable without provider access. */
export function localeRow(row) {
	const code = localeCode(row.prefix);
	const htmlLang = languageTag(row.htmlLang);
	const apiLanguageRange = languageTag(row.apiLanguageRange);
	if (row.dir !== 'ltr' && row.dir !== 'rtl') throw new Error('Invalid locale direction');
	if (row.scope !== 'full_bible' && row.scope !== 'nt') throw new Error('Invalid locale scope');
	if (!Array.isArray(row.versionIds) || row.versionIds.length === 0)
		throw new Error('Invalid locale versions');
	const versions = row.versionIds.map(versionId);
	const defaultVersion = versionId(row.defaultVersionId);
	if (!versions.includes(defaultVersion))
		throw new Error('Default version is absent from locale versions');
	return `{
		code: ${sourceLiteral(code)},
		prefix: ${sourceLiteral(code)},
		htmlLang: ${sourceLiteral(htmlLang)},
		apiLanguageRange: ${sourceLiteral(apiLanguageRange)},
		dir: ${sourceLiteral(row.dir)},
		endonym: ${sourceLiteral(text(row.endonym, 'endonym'))},
		englishName: ${sourceLiteral(text(row.englishName, 'English name'))},
		versionIds: ${sourceLiteral(versions)},
		defaultVersionId: ${sourceLiteral(defaultVersion)},
		scope: ${sourceLiteral(row.scope)},
	}`;
}

/** The code is validated before it appears in a file name or import. */
export function bookTableIndex(codes) {
	const validated = codes.map(localeCode);
	const identifiers = validated.map((code) => `BOOKS_${code.replaceAll('-', '_').toUpperCase()}`);
	if (
		new Set(validated).size !== validated.length ||
		new Set(identifiers).size !== identifiers.length
	) {
		throw new Error('Duplicate locale code or generated identifier');
	}
	return (
		`// Generated by scripts/generate-book-slugs.mjs — do not edit by hand.\n` +
		`import type { LocalizedBook } from './types';\n` +
		validated
			.map((code, i) => `import { BOOKS as ${identifiers[i]} } from ${sourceLiteral(`./${code}`)};`)
			.join('\n') +
		`\n\nexport const LOCALE_BOOK_TABLES: Readonly<\n\tRecord<string, readonly LocalizedBook[]>\n> = {\n` +
		validated.map((code, i) => `\t${sourceLiteral(code)}: ${identifiers[i]},`).join('\n') +
		`\n};\n`
	);
}
